"""Evaluate LabDesk against evals/questions.jsonl.

  python evals/run_eval.py --retrieval-only        # no model needed; the CI gate
  python evals/run_eval.py                         # full run against the configured model
  python evals/run_eval.py --set heldout           # the held-out test set (see docs/03-eval-spec.md)

Full runs write evals/results/<model>[-heldout].json and docs/report[-heldout].md.
Prices for the cost estimate: --price-in / --price-out in USD per million tokens.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
import time
from pathlib import Path

from labdesk.answer import Assistant
from labdesk.corpus import load
from labdesk.llm import ChatClient
from labdesk.retrieve import BM25
from labdesk.telemetry import cost_usd, percentile

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
TARGETS = {"recall@5": 0.90, "correctness": 0.85, "citation_validity": 0.85, "refusal_accuracy": 0.80}


SETS = {"dev": "questions.jsonl", "heldout": "heldout.jsonl"}


def load_questions(name: str = "dev") -> list[dict]:
    return [json.loads(line) for line in (HERE / SETS[name]).read_text(encoding="utf-8").splitlines() if line]


def has_facts(text: str, must: list[list[str]]) -> list[list[str]]:
    """Return the fact groups missing from the text (empty list = all present)."""
    return [group for group in must if not any(re.search(p, text, re.I) for p in group)]


def retrieval(index: BM25, questions: list[dict], k: int = 5) -> dict:
    hits, rr, misses = 0, 0.0, []
    docs = [q for q in questions if q["kind"] == "doc"]
    for q in docs:
        paths = [c.path for c, _ in index.search(q["question"], k)]
        rank = next((i for i, p in enumerate(paths, 1) if p in q["gold"]), None)
        if rank:
            hits += 1
            rr += 1 / rank
        else:
            misses.append({"id": q["id"], "retrieved": paths, "gold": q["gold"]})
    return {"recall@5": hits / len(docs), "mrr": rr / len(docs), "n": len(docs), "misses": misses}


def full(assistant: Assistant, questions: list[dict], prices: tuple[float, float]) -> dict:
    rows = []
    for q in questions:
        a = assistant.ask(q["question"])
        cited_paths = {s["path"] for s in a.sources if s["label"] in a.cited}
        row = {
            "id": q["id"], "kind": q["kind"], "question": q["question"], "answer": a.text,
            "refused": a.refused, "cited": a.cited, "invalid_citations": a.invalid_citations,
            "latency_s": round(a.latency_s, 2), "prompt_tokens": a.prompt_tokens,
            "completion_tokens": a.completion_tokens, "tool_used": a.tool_used,
        }
        if q["kind"] == "refuse":
            row["pass"] = a.refused
        else:
            missing = has_facts(a.text, q["must"])
            row["missing"] = missing
            row["correct"] = not missing and not a.refused
            if q["kind"] == "doc":
                row["citation_ok"] = bool(cited_paths & set(q["gold"])) and not a.invalid_citations
            row["pass"] = row["correct"] and (q["kind"] != "doc" or row["citation_ok"])
        rows.append(row)
        print(f"{'PASS' if row['pass'] else 'FAIL'}  {q['id']:<20} {row['latency_s']:>6.2f}s", flush=True)

    doc = [r for r in rows if r["kind"] == "doc"]
    ref = [r for r in rows if r["kind"] == "refuse"]
    tool = [r for r in rows if r["kind"] == "tool"]
    lat = [r["latency_s"] for r in rows]
    tin = sum(r["prompt_tokens"] for r in rows)
    tout = sum(r["completion_tokens"] for r in rows)
    return {
        "correctness": sum(r["correct"] for r in doc) / len(doc),
        "citation_validity": sum(r["citation_ok"] for r in doc) / len(doc),
        "over_refusal": sum(r["refused"] for r in doc) / len(doc),
        "refusal_accuracy": sum(r["pass"] for r in ref) / len(ref),
        "tool_accuracy": f"{sum(r['correct'] for r in tool)}/{len(tool)}",
        "latency_p50_s": round(percentile(lat, 0.5), 2),
        "latency_p95_s": round(percentile(lat, 0.95), 2),
        "tokens_in_per_q": round(tin / len(rows)),
        "tokens_out_per_q": round(tout / len(rows)),
        "cost_per_1000_q_usd": round(cost_usd(tin, tout, prices) / len(rows) * 1000, 4),
        "rows": rows,
    }


def report(model: str, r: dict, s: dict, prices: tuple[float, float], set_name: str = "dev") -> str:
    def mark(name: str, value: float) -> str:
        return "met" if value >= TARGETS[name] else "**missed**"

    fails = [x for x in s["rows"] if not x["pass"]]
    lines = [
        "# Evaluation report" + (" (held-out test set)" if set_name == "heldout" else ""),
        "",
        f"Model `{model}`, PyVISA 1.16.2 docs, {set_name} set, {len(s['rows'])} questions, run {time.strftime('%Y-%m-%d')}.",
        "Generated by `evals/run_eval.py`; per-question answers are in `evals/results/`.",
        "",
        "| Metric | Result | Target | |",
        "|---|---|---|---|",
        f"| Retrieval recall@5 | {r['recall@5']:.2f} (MRR {r['mrr']:.2f}) | ≥ 0.90 | {mark('recall@5', r['recall@5'])} |",
        f"| Correctness (in-scope) | {s['correctness']:.2f} | ≥ 0.85 | {mark('correctness', s['correctness'])} |",
        f"| Citation validity | {s['citation_validity']:.2f} | ≥ 0.85 | {mark('citation_validity', s['citation_validity'])} |",
        f"| Refusal accuracy (out-of-scope) | {s['refusal_accuracy']:.2f} | ≥ 0.80 | {mark('refusal_accuracy', s['refusal_accuracy'])} |",
        f"| Over-refusal (in-scope refused) | {s['over_refusal']:.2f} | ≤ 0.10 | {'met' if s['over_refusal'] <= 0.10 else '**missed**'} |",
        f"| Instrument tool | {s['tool_accuracy']} | 2/2 | {'met' if s['tool_accuracy'] == '2/2' else '**missed**'} |",
        f"| Latency p50 / p95 | {s['latency_p50_s']} s / {s['latency_p95_s']} s | p95 < 10 s | {'met' if s['latency_p95_s'] < 10 else '**missed**'} |",
        f"| Tokens per question (in / out) | {s['tokens_in_per_q']} / {s['tokens_out_per_q']} | | |",
        f"| Cost per 1,000 questions at ${prices[0]}/${prices[1]} per M tokens | ${s['cost_per_1000_q_usd']} | | |",
        "",
        f"## Failures ({len(fails)})",
        "",
    ]
    for x in fails:
        why = []
        if x.get("missing"):
            why.append("missing " + "; ".join("/".join(g) for g in x["missing"]))
        if x["kind"] == "doc" and not x.get("citation_ok"):
            why.append("citation not to a gold section" + (f" (invalid: {x['invalid_citations']})" if x["invalid_citations"] else ""))
        if x["refused"] and x["kind"] != "refuse":
            why.append("refused an in-scope question")
        if x["kind"] == "refuse" and not x["refused"]:
            why.append("answered instead of refusing")
        answer = x["answer"].replace("\n", " ")
        lines += [f"- **{x['id']}** ({', '.join(why)}): {x['question']}", f"  > {answer[:400]}", ""]
    return "\n".join(lines)


def main() -> int:
    p = argparse.ArgumentParser()
    p.add_argument("--retrieval-only", action="store_true")
    p.add_argument("--set", choices=sorted(SETS), default="dev")
    p.add_argument("--price-in", type=float, default=0.0)
    p.add_argument("--price-out", type=float, default=0.0)
    args = p.parse_args()

    questions = load_questions(args.set)
    index = BM25(load())
    r = retrieval(index, questions)
    print(f"retrieval recall@5 {r['recall@5']:.3f}  MRR {r['mrr']:.3f}  ({r['n']} questions)")
    for m in r["misses"]:
        print(f"  miss {m['id']}: got {m['retrieved']}")
    if args.retrieval_only:
        return 0 if r["recall@5"] >= TARGETS["recall@5"] else 1

    client = ChatClient()
    prices = (args.price_in, args.price_out)
    s = full(Assistant(index, client), questions, prices)
    out = HERE / "results"
    out.mkdir(exist_ok=True)
    slug = re.sub(r"[^\w.-]", "_", client.model)
    suffix = "" if args.set == "dev" else f"-{args.set}"
    data = {"model": client.model, "set": args.set, "retrieval": r, **s}
    (out / f"{slug}{suffix}.json").write_text(json.dumps(data, indent=2), encoding="utf-8")
    (ROOT / "docs" / f"report{suffix}.md").write_text(report(client.model, r, s, prices, args.set), encoding="utf-8")
    print({k: v for k, v in s.items() if k != "rows"})
    return 0


if __name__ == "__main__":
    sys.exit(main())
